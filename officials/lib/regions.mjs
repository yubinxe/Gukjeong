const norm = (s) => String(s || "").replace(/\s+/g, " ").replace(/[()（）]/g, " ").trim();
const FOREIGN = /^(미국|캐나다|일본|중국|영국|프랑스|독일|호주|뉴질랜드|싱가포르|베트남|태국|필리핀|인도네시아|말레이시아|홍콩|대만|러시아|몽골|스페인|이탈리아|스위스|네덜란드|브라질|아르헨티나|칠레|멕시코|아랍에미리트|사우디|카자흐스탄|우즈베키스탄)/;

// 소재지 문자열 → { code, level, confidence, reason }
//   level: 'sigungu' | 'sido' | 'foreign' | 'unknown'   confidence: 'exact' | 'parent' | 'approx' | 'sido' | 'none'
export function matchRegion(address) {
  const s = norm(address);
  if (!s) return { code: "X", level: "unknown", confidence: "none", reason: "소재지 없음" };
  if (FOREIGN.test(s)) return { code: "F", level: "foreign", confidence: "exact", reason: "해외 소재" };
  const tokens = s.split(" ");
  let sido = null, rest = tokens;
  for (const [code, ...names] of SIDO_ALIAS) {
    if (names.includes(tokens[0])) { sido = code; rest = tokens.slice(1); break; }
  }
  if (!sido) return { code: "X", level: "unknown", confidence: "none", reason: "시도를 읽지 못함" };
  if (sido === "29") return { code: "29010", level: "sigungu", confidence: "exact", reason: "" };
  const t0 = rest[0] || "", t1 = rest[1] || "";
  const pick = (name) => {
    const alias = SGG_ALIAS.find(([sd, n]) => sd === sido && n === name);
    if (alias) return alias[2] ? { code: alias[2], level: "sigungu", confidence: alias[3], reason: alias[3] === "exact" ? "" : `개편 전후 표기(${name})` } : null;
    const hit = Object.entries(SIGUNGU).find(([c, n]) => n === name && sidoOf(c) === sido);
    return hit ? { code: hit[0], level: "sigungu", confidence: "exact", reason: "" } : null;
  };
  // '수원시 장안구' → 수원시장안구, 그다음 '수원시' 단독, 그다음 첫 낱말
  const found = (/시$/.test(t0) && /구$/.test(t1) && pick(t0 + t1)) || pick(t0);
  if (found) return found;
  if (/시$/.test(t0) && /구$/.test(t1)) {
    const parent = Object.entries(SIGUNGU).find(([c, n]) => n.startsWith(t0) && sidoOf(c) === sido);
    if (parent && !Object.values(SIGUNGU).some((n) => n === t0 + t1)) {
      // 구가 여럿인 시인데 그 구 이름을 모르면 시도까지만 센다
      return { code: sido, level: "sido", confidence: "sido", reason: `구 이름 미확인(${t0} ${t1})` };
    }
  }
  return { code: sido, level: "sido", confidence: "sido", reason: `시군구 미확인(${t0 || "표기 없음"})` };
}
