export function regionName(code, { short = false } = {}) {
  if (!code) return "지역 미확인";
  if (code === "F") return "해외";
  if (code === "X") return "지역 미확인";
  if (code.length === 2) return short ? SIDO_SHORT[code] : SIDO[code];
  const n = SIGUNGU[code];
  if (!n) return code;
  const city = n.match(/^(.+시)(.+구)$/); // 수원시장안구 → 수원시 장안구
  return `${short ? SIDO_SHORT[sidoOf(code)] : SIDO[sidoOf(code)]} ${city ? `${city[1]} ${city[2]}` : n}`;
}

